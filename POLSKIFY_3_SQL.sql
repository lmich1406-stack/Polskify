-- Run in Supabase SQL Editor after previous Polskify patches.

alter table public.profiles add column if not exists banned boolean not null default false;

create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  name text not null,
  starts_at date not null,
  ends_at date not null,
  active boolean not null default true
);

create table if not exists public.season_entries (
  season_id bigint not null references public.seasons(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  points integer not null default 0,
  primary key(season_id,user_id)
);

alter table public.seasons enable row level security;
alter table public.season_entries enable row level security;
grant select on public.seasons, public.season_entries to authenticated;
drop policy if exists "seasons_read" on public.seasons;
create policy "seasons_read" on public.seasons for select to authenticated using(true);
drop policy if exists "season_entries_read" on public.season_entries;
create policy "season_entries_read" on public.season_entries for select to authenticated using(true);

insert into public.seasons(name,starts_at,ends_at,active)
select
  'Sezon ' || to_char(current_date,'MM/YYYY'),
  date_trunc('month',current_date)::date,
  (date_trunc('month',current_date)+interval '1 month - 1 day')::date,
  true
where not exists (
  select 1 from public.seasons
  where current_date between starts_at and ends_at
);

create or replace function public.award_special_quiz_xp(
  p_quiz_code text,
  p_score integer,
  p_total integer
)
returns table(
  xp_awarded integer,
  total_xp integer,
  weekly_xp integer,
  league text,
  week_key date,
  region_passed boolean,
  already_rewarded boolean
)
language plpgsql
security definer
set search_path=public
as $$
declare
  v_uid uuid:=auth.uid();
  v_reward integer;
  v_week date:=current_date-((extract(isodow from current_date)::int)-1);
  v_exists boolean;
  v_league text;
begin
  if v_uid is null then raise exception 'Not authenticated'; end if;
  if p_quiz_code not in ('SPECIAL_RANDOM','SPECIAL_CAPITALS','SPECIAL_RIVERS','SPECIAL_NEIGHBORS','SPECIAL_FLAGS','SPECIAL_LANDMARKS') then
    raise exception 'Invalid quiz';
  end if;
  if p_total<>10 or p_score<0 or p_score>10 then raise exception 'Invalid result'; end if;

  insert into public.progress(user_id) values(v_uid) on conflict(user_id) do nothing;
  select exists(select 1 from public.quiz_rewards where user_id=v_uid and region_code=p_quiz_code and reward_day=current_date) into v_exists;

  if v_exists then
    select p.xp,p.weekly_xp,p.league,p.week_key into total_xp,weekly_xp,league,week_key
    from public.progress p where p.user_id=v_uid;
    xp_awarded:=0; region_passed:=false; already_rewarded:=true; return next; return;
  end if;

  v_reward:=(p_score*10)+case when p_score>=5 then 20 else 0 end;

  update public.progress p
  set xp=p.xp+v_reward,
      weekly_xp=case when p.week_key is distinct from v_week then v_reward else p.weekly_xp+v_reward end,
      week_key=v_week,
      updated_at=now()
  where p.user_id=v_uid;

  update public.progress p set league=case when weekly_xp>=1200 then 'gold' when weekly_xp>=500 then 'silver' else 'bronze' end
  where p.user_id=v_uid;

  insert into public.quiz_rewards(user_id,region_code,reward_day,score,xp_awarded)
  values(v_uid,p_quiz_code,current_date,p_score,v_reward);

  select p.xp,p.weekly_xp,p.league,p.week_key into total_xp,weekly_xp,league,week_key
  from public.progress p where p.user_id=v_uid;

  insert into public.league_entries(user_id,display_name,weekly_xp,league,week_key,updated_at)
  select v_uid,coalesce(pr.display_name,split_part(u.email,'@',1),'gracz'),weekly_xp,league,week_key,now()
  from auth.users u left join public.profiles pr on pr.id=u.id where u.id=v_uid
  on conflict(user_id) do update set weekly_xp=excluded.weekly_xp,league=excluded.league,week_key=excluded.week_key,updated_at=now();

  xp_awarded:=v_reward; region_passed:=false; already_rewarded:=false; return next;
end;
$$;
revoke all on function public.award_special_quiz_xp(text,integer,integer) from public,anon;
grant execute on function public.award_special_quiz_xp(text,integer,integer) to authenticated;

create or replace function public.get_current_season()
returns table(name text, ends_at date, points integer)
language plpgsql security definer set search_path=public
as $$
declare v_uid uuid:=auth.uid(); v_sid bigint;
begin
  select id,s.name,s.ends_at into v_sid,name,ends_at from public.seasons s
  where current_date between s.starts_at and s.ends_at order by s.id desc limit 1;
  if v_sid is null then return; end if;
  select coalesce(se.points,0) into points from public.season_entries se where se.season_id=v_sid and se.user_id=v_uid;
  points:=coalesce(points,0); return next;
end; $$;
grant execute on function public.get_current_season() to authenticated;

create or replace function public.quiz_reward_to_season()
returns trigger language plpgsql security definer set search_path=public as $$
declare v_sid bigint;
begin
  select id into v_sid from public.seasons where new.reward_day between starts_at and ends_at order by id desc limit 1;
  if v_sid is not null then
    insert into public.season_entries(season_id,user_id,points) values(v_sid,new.user_id,new.xp_awarded)
    on conflict(season_id,user_id) do update set points=public.season_entries.points+excluded.points;
  end if;
  return new;
end; $$;
drop trigger if exists trg_quiz_reward_season on public.quiz_rewards;
create trigger trg_quiz_reward_season after insert on public.quiz_rewards for each row execute function public.quiz_reward_to_season();

create or replace function public.admin_list_users()
returns table(user_id uuid,email text,xp integer,streak_count integer,banned boolean)
language plpgsql security definer set search_path=public as $$
declare v_admin boolean;
begin
  select is_admin into v_admin from public.profiles where id=auth.uid();
  if coalesce(v_admin,false)=false then raise exception 'Admin only'; end if;
  return query
  select u.id,u.email,coalesce(p.xp,0),coalesce(p.streak_count,0),coalesce(pr.banned,false)
  from auth.users u
  left join public.progress p on p.user_id=u.id
  left join public.profiles pr on pr.id=u.id
  order by u.created_at desc limit 200;
end; $$;
grant execute on function public.admin_list_users() to authenticated;

create or replace function public.admin_user_action(p_user_id uuid,p_action text,p_value text default null)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_admin boolean;
begin
  select is_admin into v_admin from public.profiles where id=auth.uid();
  if coalesce(v_admin,false)=false then raise exception 'Admin only'; end if;

  if p_action='ban' then update public.profiles set banned=true where id=p_user_id;
  elsif p_action='unban' then update public.profiles set banned=false where id=p_user_id;
  elsif p_action='resetstreak' then update public.progress set streak_count=0,streak_last_day=null where user_id=p_user_id;
  elsif p_action='setxp' then update public.progress set xp=greatest(0,coalesce(p_value,'0')::integer) where user_id=p_user_id;
  else raise exception 'Unknown action';
  end if;
  return true;
end; $$;
grant execute on function public.admin_user_action(uuid,text,text) to authenticated;


