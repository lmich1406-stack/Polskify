create or replace function public.start_secure_quiz(p_quiz_code text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_ids jsonb; v_questions jsonb; v_session uuid; v_banned boolean;
begin
 if v_uid is null then raise exception 'Not authenticated'; end if;
 select coalesce(banned,false) into v_banned from public.profiles where id=v_uid;
 if v_banned then raise exception 'Account banned'; end if;

 if p_quiz_code='SPECIAL_RANDOM' then
   select jsonb_agg(id),jsonb_agg(jsonb_build_object('id',id,'q',question,'a',options))
   into v_ids,v_questions from(
     select id,question,options from public.quiz_questions
     where quiz_code in('ZP','PM','WN','PD','LB','KP','WP','MZ','LD','LU','DS','OP','SK','SL','MA','PK')
     order by random() limit 10
   )q;
 else
   select jsonb_agg(id),jsonb_agg(jsonb_build_object('id',id,'q',question,'a',options))
   into v_ids,v_questions from(
     select id,question,options from public.quiz_questions where quiz_code=p_quiz_code order by random() limit 10
   )q;
 end if;

 if v_ids is null or jsonb_array_length(v_ids)<>10 then raise exception 'Quiz unavailable'; end if;
 insert into public.quiz_sessions(user_id,quiz_code,question_ids) values(v_uid,p_quiz_code,v_ids) returning id into v_session;
 return jsonb_build_object('session_id',v_session,'questions',v_questions);
end;$$;
revoke all on function public.start_secure_quiz(text) from public,anon;
grant execute on function public.start_secure_quiz(text) to authenticated;

create or replace function public.submit_secure_answer(p_session_id uuid,p_question_index integer,p_answer_index integer)
returns table(correct boolean,correct_index integer)
language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_session public.quiz_sessions%rowtype; v_qid text; v_key text:=p_question_index::text;
begin
 if v_uid is null then raise exception 'Not authenticated'; end if;
 if p_question_index<0 or p_question_index>9 or p_answer_index<0 or p_answer_index>3 then raise exception 'Invalid answer'; end if;
 select * into v_session from public.quiz_sessions where id=p_session_id and user_id=v_uid for update;
 if not found or v_session.completed then raise exception 'Invalid quiz session'; end if;
 if v_session.answers ? v_key then raise exception 'Question already answered'; end if;
 v_qid:=v_session.question_ids->>p_question_index;
 select q.correct_index into correct_index from public.quiz_questions q where q.id=v_qid;
 if correct_index is null then raise exception 'Question unavailable'; end if;
 correct:=p_answer_index=correct_index;
 update public.quiz_sessions set answers=jsonb_set(answers,array[v_key],to_jsonb(correct),true) where id=p_session_id;
 return next;
end;$$;
revoke all on function public.submit_secure_answer(uuid,integer,integer) from public,anon;
grant execute on function public.submit_secure_answer(uuid,integer,integer) to authenticated;

create or replace function public.finalize_secure_quiz(p_session_id uuid)
returns table(score integer,xp_awarded integer,total_xp integer,weekly_xp integer,league text,week_key date,region_passed boolean,already_rewarded boolean)
language plpgsql security definer set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_session public.quiz_sessions%rowtype; v_week date:=current_date-((extract(isodow from current_date)::int)-1); v_reward integer; v_exists boolean; v_is_region boolean;
begin
 if v_uid is null then raise exception 'Not authenticated'; end if;
 select * into v_session from public.quiz_sessions where id=p_session_id and user_id=v_uid for update;
 if not found then raise exception 'Invalid quiz session'; end if;
 select count(*)::integer into score from jsonb_each_text(v_session.answers)x where x.value='true';
 if jsonb_object_length(v_session.answers)<>10 then raise exception 'Quiz not complete'; end if;
 v_is_region:=v_session.quiz_code in('ZP','PM','WN','PD','LB','KP','WP','MZ','LD','LU','DS','OP','SK','SL','MA','PK');
 region_passed:=v_is_region and score>=5;
 insert into public.progress(user_id) values(v_uid) on conflict(user_id) do nothing;
 select exists(select 1 from public.quiz_rewards where user_id=v_uid and region_code=v_session.quiz_code and reward_day=current_date) into v_exists;
 if v_exists then xp_awarded:=0;already_rewarded:=true;
 else
   v_reward:=(score*10)+case when score>=5 then(case when v_is_region then 25 else 20 end)else 0 end;
   xp_awarded:=v_reward;already_rewarded:=false;
   update public.progress p set xp=coalesce(p.xp,0)+v_reward,
     weekly_xp=case when p.week_key is distinct from v_week then v_reward else coalesce(p.weekly_xp,0)+v_reward end,
     week_key=v_week,
     passed_regions=case when region_passed then jsonb_set(coalesce(p.passed_regions,'{}'::jsonb),array[v_session.quiz_code],'true'::jsonb,true) else coalesce(p.passed_regions,'{}'::jsonb) end,
     updated_at=now() where p.user_id=v_uid;
   update public.progress p set league=case when p.weekly_xp>=1200 then 'gold' when p.weekly_xp>=500 then 'silver' else 'bronze' end where p.user_id=v_uid;
   insert into public.quiz_rewards(user_id,region_code,reward_day,score,xp_awarded) values(v_uid,v_session.quiz_code,current_date,score,v_reward);
 end if;
 update public.quiz_sessions set completed=true where id=p_session_id;
 select p.xp,p.weekly_xp,p.league,p.week_key into total_xp,weekly_xp,league,week_key from public.progress p where p.user_id=v_uid;
 insert into public.league_entries(user_id,display_name,weekly_xp,league,week_key,updated_at)
 select v_uid,coalesce(pr.display_name,split_part(u.email,'@',1),'gracz'),weekly_xp,league,week_key,now()
 from auth.users u left join public.profiles pr on pr.id=u.id where u.id=v_uid
 on conflict(user_id) do update set display_name=excluded.display_name,weekly_xp=excluded.weekly_xp,league=excluded.league,week_key=excluded.week_key,updated_at=now();
 return next;
end;$$;
revoke all on function public.finalize_secure_quiz(uuid) from public,anon;
grant execute on function public.finalize_secure_quiz(uuid) to authenticated;
